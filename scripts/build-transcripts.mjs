#!/usr/bin/env node
// Builds frontend/src/content/transcripts.ts from the "Script:" sections of docs/recording-scripts/*.md.
// Usage: node scripts/build-transcripts.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'docs', 'recording-scripts');
const out = join(root, 'frontend', 'src', 'content', 'transcripts.ts');

const transcripts = {};
for (const file of readdirSync(dir).filter(f => f.endsWith('.md')).sort()) {
    const text = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n');
    // split into lessons on "## m<n>-l<n> | Title"
    const parts = text.split(/^## (?=m\d+-l\d+ \|)/m).slice(1);
    for (const part of parts) {
        const id = part.match(/^(m\d+-l\d+) \|/)[1];
        const start = part.indexOf('**Script:**');
        if (start < 0) { console.warn(`no script for ${id}`); continue; }
        let body = part.slice(start + '**Script:**'.length);
        const end = body.search(/^\*\*(Pause-and-try prompt|Recap line|Bridge|Word count):\*\*/m);
        if (end >= 0) body = body.slice(0, end);
        const paras = body
            .replace(/\[[^\]]*\]/g, '')                 // stage directions
            .split(/\n{2,}/)
            .map(p => p.replace(/\s*\n\s*/g, ' ').replace(/[ \t]{2,}/g, ' ').trim())
            .filter(p => p && p !== '---');
        if (paras.length) transcripts[id] = paras;
    }
}

const ids = Object.keys(transcripts);
const header = `// GENERATED by scripts/build-transcripts.mjs from docs/recording-scripts/*.md. Do not edit by hand.
// Lessons without an entry have no transcript tab.

export const TRANSCRIPTS: Record<string, string[]> = `;
writeFileSync(out, header + JSON.stringify(transcripts, null, 4) + ';\n\nexport const getTranscript = (itemId: string): string[] | undefined => TRANSCRIPTS[itemId];\n');
console.log(`Wrote ${ids.length} transcripts to ${out}`);
